func populateHasGitToken(projects []models.Project) {
	for i := range projects {
		projects[i].HasGitToken = projects[i].GitToken != ""
	}
}

func generateWebhookSecret() string {
	b := make([]byte, 20)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

func setProjectFlags(p *models.Project) {
	p.HasGitToken = p.GitToken != ""
	p.HasWebhook = p.WebhookSecret != ""
}

