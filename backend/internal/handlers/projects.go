func StreamBuildLogs(c *gin.Context) {
	userID := c.GetString("user_id")
	var project models.Project
	if err := database.DB.Where("id = ? AND user_id = ?", c.Param("id"), userID).First(&project).Error; err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "project not found"})
		return
	}

	var dep models.Deployment
	if err := database.DB.Where("project_id = ? AND status IN ?", project.ID, []string{string(models.StatusPending), string(models.StatusBuilding)}).Order("started_at desc").First(&dep).Error; err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "no active build"})
		return
	}

	c.Header("Content-Type", "text/event-stream")
	c.Header("Cache-Control", "no-cache")
	c.Header("Connection", "keep-alive")
	c.Header("X-Accel-Buffering", "no")

	ch := logbroker.Global.Subscribe(dep.ID)
	defer logbroker.Global.Unsubscribe(dep.ID, ch)

	ctx := c.Request.Context()
	for {
		select {
		case line, ok := <-ch:
			if !ok {
				fmt.Fprintf(c.Writer, "event: done\ndata: \n\n")
				c.Writer.(http.Flusher).Flush()
				return
			}
			fmt.Fprintf(c.Writer, "data: %s\n\n", strings.ReplaceAll(line, "\n", "\ndata: "))
			c.Writer.(http.Flusher).Flush()
		case <-ctx.Done():
			return
		}
	}
}

func StreamContainerLogs(c *gin.Context) {
	userID := c.GetString("user_id")
	var project models.Project
	if err := database.DB.Where("id = ? AND user_id = ?", c.Param("id"), userID).First(&project).Error; err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "project not found"})
		return
	}

	var dep models.Deployment
	if err := database.DB.Where("project_id = ?", project.ID).Order("started_at desc").First(&dep).Error; err != nil || dep.ContainerID == "" {
		c.JSON(http.StatusBadRequest, gin.H{"message": "no running container"})
		return
	}

	c.Header("Content-Type", "text/event-stream")
	c.Header("Cache-Control", "no-cache")
	c.Header("Connection", "keep-alive")

	ctx, cancel := context.WithCancel(c.Request.Context())
	defer cancel()

	reader, err := docker.StreamLogs(ctx, dep.ContainerID)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": err.Error()})
		return
	}
	defer reader.Close()

	scanner := bufio.NewScanner(reader)
	for scanner.Scan() {
		line := scanner.Text()
		if len(line) > 8 {
			line = line[8:]
		}
		fmt.Fprintf(c.Writer, "data: %s\n\n", line)
		c.Writer.(http.Flusher).Flush()
	}
}
