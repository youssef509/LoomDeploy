func DeployProject(c *gin.Context) {
	userID := c.GetString("user_id")
	var project models.Project
	if err := database.DB.Where("id = ? AND user_id = ?", c.Param("id"), userID).First(&project).Error; err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "project not found"})
		return
	}

	var activeCount int64
	database.DB.Model(&models.Deployment{}).
		Where("project_id = ? AND status IN ?", project.ID, []string{string(models.StatusPending), string(models.StatusBuilding)}).
		Count(&activeCount)
	if activeCount > 0 {
		c.JSON(http.StatusConflict, gin.H{"message": "a deployment is already in progress"})
		return
	}

	var envVars []models.EnvVar
	database.DB.Where("project_id = ?", project.ID).Find(&envVars)

	dep := models.Deployment{
		ID:        uuid.NewString(),
		ProjectID: project.ID,
		Status:    models.StatusPending,
		StartedAt: time.Now(),
	}
	database.DB.Create(&dep)
	startDeployGoroutine(dep, project, envVars, "")
	c.JSON(http.StatusAccepted, dep)
}

