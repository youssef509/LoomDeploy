func sendWebhookNotification(webhookURL, projectName string, status models.DeploymentStatus, sha string, dur time.Duration) {
	if webhookURL == "" {
		return
	}
	icon := "✅"
	if status != models.StatusRunning {
		icon = "❌"
	}
	msg := fmt.Sprintf("%s **%s** — deployment `%s`", icon, projectName, status)
	if len(sha) >= 7 {
		msg += fmt.Sprintf(" · commit `%s`", sha[:7])
	}
	dur = dur.Round(time.Second)
	m := int(dur.Minutes())
	s := int(dur.Seconds()) % 60
	if m > 0 {
		msg += fmt.Sprintf(" · took %dm %ds", m, s)
	} else {
		msg += fmt.Sprintf(" · took %ds", s)
	}
	payload, _ := json.Marshal(map[string]string{
		"text":    msg,
		"content": msg,
	})
	req, err := http.NewRequest(http.MethodPost, webhookURL, bytes.NewReader(payload))
	if err != nil {
		log.Printf("notification: bad webhook URL: %v", err)
		return
	}
	req.Header.Set("Content-Type", "application/json")
	client := &http.Client{Timeout: 5 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		log.Printf("notification webhook failed: %v", err)
		return
	}
	resp.Body.Close()
}

