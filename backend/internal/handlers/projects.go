func startDeployGoroutine(dep models.Deployment, project models.Project, envVars []models.EnvVar, overrideSHA string) {
	go func() {
		var logs strings.Builder
		success := false
		containerID := ""
		resolvedSHA := ""

		publish := func(line string) {
			logs.WriteString(line)
			logbroker.Global.Publish(dep.ID, line)
		}

		defer func() {
			if r := recover(); r != nil {
				msg := fmt.Sprintf("\nFATAL: unexpected panic during deployment: %v\n", r)
				logs.WriteString(msg)
				logbroker.Global.Publish(dep.ID, msg)
			}
			logbroker.Global.Close(dep.ID)
			now := time.Now()
			status := models.StatusFailed
			if success {
				status = models.StatusRunning
			}
			database.DB.Model(&dep).Updates(models.Deployment{
				Status:      status,
				ContainerID: containerID,
				BuildLogs:   logs.String(),
				FinishedAt:  &now,
			})
			go sendWebhookNotification(project.NotificationWebhookURL, project.Name, status, resolvedSHA, now.Sub(dep.StartedAt))
		}()

		buildDir := filepath.Join(os.TempDir(), "builds", project.ID)
		_ = os.RemoveAll(buildDir)
		defer os.RemoveAll(buildDir)

		database.DB.Model(&dep).Update("status", models.StatusBuilding)

		if project.SourceType == models.SourceGit {
			token := project.GitToken
			if token == "" {
				if parsed, err := url.Parse(project.RepositoryURL); err == nil && parsed.Host != "" {
					host := strings.ToLower(parsed.Host)
					if idx := strings.LastIndex(host, ":"); idx != -1 {
						host = host[:idx]
					}
					var st models.SourceToken
					if database.DB.Where("provider = ?", host).First(&st).Error == nil {
						token = st.Token
					}
					// Fall back to GitHub App installation token
					if token == "" && strings.Contains(host, "github.com") {
						if ghTok, err := GetGitHubCloneToken(); err == nil && ghTok != "" {
							token = ghTok
						}
					}
				}
			}

			cloneURL := project.RepositoryURL
			if token != "" {
				if parsed, err := url.Parse(cloneURL); err == nil {
					parsed.User = url.UserPassword("x-access-token", token)
					cloneURL = parsed.String()
				}
			}

			cloneArgs := []string{"clone", "--branch", project.Branch}
			if overrideSHA == "" {
				cloneArgs = append(cloneArgs, "--depth=1")
			}
			cloneArgs = append(cloneArgs, cloneURL, buildDir)

			publish(fmt.Sprintf("Cloning %s (%s)...\n", project.RepositoryURL, project.Branch))
			out, err := exec.Command("git", cloneArgs...).CombinedOutput()
			publish(string(out))
			if err != nil {
				outStr := strings.ToLower(string(out))
				isAuthErr := strings.Contains(outStr, "authentication failed") ||
					strings.Contains(outStr, "could not read username") ||
					strings.Contains(outStr, "permission denied") ||
					strings.Contains(outStr, "repository not found") ||
					strings.Contains(outStr, "invalid username or password") ||
					strings.Contains(outStr, "remote: not found")
				if isAuthErr {
					publish("ERROR: This repository may be private. Add a token for this provider in Settings → Source Control.\n")
				} else {
					publish(fmt.Sprintf("git clone failed: %v\n", err))
				}
				return
			}

			if overrideSHA != "" {
				publish(fmt.Sprintf("Rolling back to commit %s...\n", overrideSHA[:7]))
				checkOut, checkErr := exec.Command("git", "-C", buildDir, "checkout", overrideSHA).CombinedOutput()
				publish(string(checkOut))
				if checkErr != nil {
					publish(fmt.Sprintf("ERROR: could not checkout %s: %v\n", overrideSHA, checkErr))
					return
				}
			}

			shaBytes, _ := exec.Command("git", "-C", buildDir, "rev-parse", "HEAD").Output()
			resolvedSHA = strings.TrimSpace(string(shaBytes))
			if resolvedSHA != "" {
				database.DB.Model(&dep).Update("commit_sha", resolvedSHA)
				publish(fmt.Sprintf("Commit: %s\n", resolvedSHA[:7]))
			}

			if _, statErr := os.Stat(filepath.Join(buildDir, "Dockerfile")); os.IsNotExist(statErr) {
				if project.DockerfileContent != "" {
					publish("No Dockerfile in repo — using project's custom Dockerfile override...\n")
					if werr := os.WriteFile(filepath.Join(buildDir, "Dockerfile"), []byte(project.DockerfileContent), 0644); werr != nil {
						publish(fmt.Sprintf("ERROR: could not write Dockerfile: %v\n", werr))
						return
					}
				} else {
					framework := docker.DetectFramework(buildDir)
					if framework == "" {
						publish("ERROR: No Dockerfile found and framework could not be auto-detected.\n")
						publish("Add a Dockerfile to your repo root, or set a custom Dockerfile in project Settings → Dockerfile Override.\n")
						publish("Supported auto-detect: Node.js (package.json), Python (requirements.txt/pyproject.toml), Go (go.mod), Ruby (Gemfile), PHP (composer.json), Java Maven (pom.xml), Java Gradle (build.gradle), Static HTML (index.html — served via nginx on port 80).\n")
						return
					}
					publish(fmt.Sprintf("No Dockerfile found — auto-detected framework: %s. Injecting template...\n", framework))
					tmpl := docker.DockerfileTemplate(framework, buildDir, project.ContainerPort)
					if werr := os.WriteFile(filepath.Join(buildDir, "Dockerfile"), []byte(tmpl), 0644); werr != nil {
						publish(fmt.Sprintf("ERROR: could not write Dockerfile: %v\n", werr))
						return
					}
				}
			}
		} else {
			publish("Upload-based deployment: no source directory found\n")
			return
		}

		imageTag := docker.TagForProject(project.ID)
		publish(fmt.Sprintf("Building image %s...\n", imageTag))

		archive, err := docker.CreateBuildArchive(buildDir)
		if err != nil {
			publish(fmt.Sprintf("Archive error: %v\n", err))
			return
		}
		defer archive.Close()

		ctx := context.Background()
		buildOut, err := docker.BuildImage(ctx, archive, imageTag)
		if err != nil {
			publish(fmt.Sprintf("Build error: %v\n", err))
			return
		}
		defer buildOut.Close()

		scanner := bufio.NewScanner(buildOut)
		for scanner.Scan() {
			line := scanner.Text()
			var msg map[string]json.RawMessage
			if json.Unmarshal([]byte(line), &msg) == nil {
				if errRaw, ok := msg["error"]; ok {
					var errStr string
					_ = json.Unmarshal(errRaw, &errStr)
					publish("ERROR: " + errStr + "\n")
					return
				}
				if streamRaw, ok := msg["stream"]; ok {
					var s string
					_ = json.Unmarshal(streamRaw, &s)
					if s != "" {
						publish(s)
					}
				} else if statusRaw, ok := msg["status"]; ok {
					var s string
					_ = json.Unmarshal(statusRaw, &s)
					if idRaw, ok2 := msg["id"]; ok2 {
						var id string
						_ = json.Unmarshal(idRaw, &id)
						publish(s + " " + id + "\n")
					} else {
						publish(s + "\n")
					}
				}
			} else {
				publish(line + "\n")
			}
		}

		publish("Starting container...\n")

		envSlice := make([]string, 0, len(envVars))
		for _, e := range envVars {
			envSlice = append(envSlice, fmt.Sprintf("%s=%s", e.Key, e.Value))
		}

		var extraDomains []models.ProjectDomain
		database.DB.Where("project_id = ?", project.ID).Find(&extraDomains)
		extraSlice := make([]string, 0, len(extraDomains))
		for _, d := range extraDomains {
			extraSlice = append(extraSlice, d.Domain)
		}

		cid, err := docker.RunContainer(ctx, docker.RunConfig{
			ProjectID:     project.ID,
			ImageTag:      imageTag,
			Domain:        project.Domain,
			ExtraDomains:  extraSlice,
			ContainerPort: project.ContainerPort,
			EnvVars:       envSlice,
			CPULimit:      project.CPULimit,
			MemoryLimitMB: int64(project.MemoryLimitMB),
		})
		if err != nil {
			publish(fmt.Sprintf("Container run error: %v\n", err))
			return
		}

		retiredAt := time.Now()
		database.DB.Model(&models.Deployment{}).
			Where("project_id = ? AND id != ? AND status = ?", project.ID, dep.ID, models.StatusRunning).
			Updates(map[string]interface{}{"status": models.StatusStopped, "finished_at": &retiredAt})

		containerID = cid
		success = true
		publish(fmt.Sprintf("Deployment complete. Container: %s\n", cid[:12]))
	}()
}

