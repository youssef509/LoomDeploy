func CreateProject(c *gin.Context) {
	userID := c.GetString("user_id")
	var req createProjectRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": err.Error()})
		return
	}
	if req.Branch == "" {
		req.Branch = "main"
	}
	if req.ContainerPort == 0 {
		req.ContainerPort = 3000
	}
	if req.SourceType == "" {
		req.SourceType = models.SourceGit
	}

	domain := autoGenerateDomain(req.Name)
	isGenerated := true

	project := models.Project{
		ID:                uuid.NewString(),
		UserID:            userID,
		Name:              req.Name,
		Domain:            domain,
		IsGeneratedDomain: isGenerated,
		SourceType:        req.SourceType,
		RepositoryURL:  req.RepositoryURL,
		Branch:         req.Branch,
		ContainerPort:  req.ContainerPort,
		GitToken:       req.GitToken,
		WebhookSecret:  generateWebhookSecret(),
		CPULimit:            req.CPULimit,
		MemoryLimitMB:       req.MemoryLimitMB,
		HealthCheckURL:      req.HealthCheckURL,
		DockerfileContent:   req.DockerfileContent,
		CreatedAt:           time.Now(),
	}
	if err := database.DB.Create(&project).Error; err != nil {
		c.JSON(http.StatusConflict, gin.H{"message": "project with that domain already exists"})
		return
	}
	setProjectFlags(&project)
	c.JSON(http.StatusCreated, project)
}

func UpdateProject(c *gin.Context) {
	userID := c.GetString("user_id")
	var project models.Project
	if err := database.DB.Where("id = ? AND user_id = ?", c.Param("id"), userID).First(&project).Error; err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "project not found"})
		return
	}

	var req updateProjectRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": err.Error()})
		return
	}

	updates := map[string]interface{}{}
	if req.Name != nil && *req.Name != "" {
		updates["name"] = *req.Name
	}
	if req.Domain != nil && *req.Domain != "" {
		updates["domain"] = *req.Domain
	}
	if req.RepositoryURL != nil {
		updates["repository_url"] = *req.RepositoryURL
	}
	if req.Branch != nil {
		updates["branch"] = *req.Branch
	}
	if req.ContainerPort != nil && *req.ContainerPort > 0 {
		updates["container_port"] = *req.ContainerPort
	}
	if req.GitToken != nil {
		updates["git_token"] = *req.GitToken
	}
	if req.NotificationWebhookURL != nil {
		updates["notification_webhook_url"] = *req.NotificationWebhookURL
	}
	if req.CPULimit != nil {
		updates["cpu_limit"] = *req.CPULimit
	}
	if req.MemoryLimitMB != nil {
		updates["memory_limit_mb"] = *req.MemoryLimitMB
	}
	if req.HealthCheckURL != nil {
		updates["health_check_url"] = *req.HealthCheckURL
	}
	if req.DockerfileContent != nil {
		updates["dockerfile_content"] = *req.DockerfileContent
	}

	if len(updates) == 0 {
		c.JSON(http.StatusBadRequest, gin.H{"message": "no fields to update"})
		return
	}

	if err := database.DB.Model(&project).Updates(updates).Error; err != nil {
		c.JSON(http.StatusConflict, gin.H{"message": "update failed: domain may already be taken"})
		return
	}

	database.DB.Where("id = ?", project.ID).First(&project)
	setProjectFlags(&project)
	c.JSON(http.StatusOK, project)
}

